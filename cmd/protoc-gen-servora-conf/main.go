// protoc-gen-servora-conf 为配置消息及其子消息生成 Apply 处理方法。
package main

import (
	"fmt"
	"hash/fnv"
	"math"
	"sort"
	"strconv"
	"time"

	validate "buf.build/gen/go/bufbuild/protovalidate/protocolbuffers/go/buf/validate"
	confv1 "github.com/Servora-Kit/servora/api/gen/go/servora/conf/v1"
	"github.com/Servora-Kit/servora/cmd/internal/protoreach"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

const generatedFileSuffix = ".pb.servora-conf.go"

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		return generate(gen)
	})
}

func generate(gen *protogen.Plugin) error {
	// 业务 RPC 的请求与响应不会仅因引用配置子消息而生成 Apply。
	rpcTypes := make(map[protoreflect.FullName]bool)
	for _, file := range gen.Files {
		for _, svc := range file.Services {
			for _, method := range svc.Methods {
				rpcTypes[method.Desc.Input().FullName()] = true
				rpcTypes[method.Desc.Output().FullName()] = true
			}
		}
	}
	// 从配置注解收集子消息，再向上找到未标注的配置容器；普通 RPC 的值校验不属于配置图。
	graph := make(map[protoreflect.FullName]bool)
	for _, file := range gen.Files {
		for _, m := range flatten(file.Messages) {
			if section(m.Desc) || hasConfField(m.Desc) {
				markConfig(m.Desc, graph)
			}
		}
	}
	// 向上补齐配置根与中间容器，再从每个新容器纳入全部子配置。
	// 这样同一根里的 Trace 等仅带 buf.validate 的消息也能执行 Apply。
	for {
		before := len(graph)
		for _, file := range gen.Files {
			for _, m := range flatten(file.Messages) {
				if graph[m.Desc.FullName()] || rpcTypes[m.Desc.FullName()] || m.Desc.IsMapEntry() {
					continue
				}
				if protoreach.NeedsConfig(m.Desc, func(fd protoreflect.FieldDescriptor) bool {
					child := protoreach.ConfigChild(fd)
					return child != nil && graph[child.FullName()]
				}, map[protoreflect.FullName]bool{}) {
					markConfig(m.Desc, graph)
				}
			}
		}
		if len(graph) == before {
			break
		}
	}
	messageIndex := make(map[protoreflect.FullName]*protogen.Message)
	for _, file := range gen.Files {
		for _, m := range flatten(file.Messages) {
			messageIndex[m.Desc.FullName()] = m
		}
	}
	for _, file := range gen.Files {
		if !file.Generate {
			continue
		}
		localRoots := false
		for _, m := range flatten(file.Messages) {
			if section(m.Desc) || hasConfField(m.Desc) {
				localRoots = true
				break
			}
		}
		var messages []*protogen.Message
		for _, m := range flatten(file.Messages) {
			if m.Desc.IsMapEntry() {
				continue
			}
			if rpcTypes[m.Desc.FullName()] && !graph[m.Desc.FullName()] {
				continue
			}
			if graph[m.Desc.FullName()] && (localRoots || hasStandaloneApply(m.Desc)) {
				messages = append(messages, m)
			}
		}
		if len(messages) == 0 {
			continue
		}
		sort.Slice(messages, func(i, j int) bool { return messages[i].Desc.FullName() < messages[j].Desc.FullName() })
		g := gen.NewGeneratedFile(file.GeneratedFilenamePrefix+generatedFileSuffix, file.GoImportPath)
		g.P("// Code generated by protoc-gen-servora-conf. DO NOT EDIT.")
		g.P("// source: ", file.Desc.Path())
		g.P()
		g.P("package ", file.GoPackageName)
		g.P()
		checks := &nilCheckEmitter{filePath: file.Desc.Path(), messages: messageIndex, pending: make(map[protoreflect.FullName]*protogen.Message), emitted: make(map[protoreflect.FullName]bool)}
		for _, m := range messages {
			if err := emitApply(g, m, graph, checks); err != nil {
				return err
			}
		}
		if err := checks.emitAll(g); err != nil {
			return err
		}
	}
	return nil
}

func flatten(messages []*protogen.Message) []*protogen.Message {
	var all []*protogen.Message
	for _, m := range messages {
		all = append(all, m)
		all = append(all, flatten(m.Messages)...)
	}
	return all
}

func section(md protoreflect.MessageDescriptor) bool {
	opts := md.Options()
	return opts != nil && proto.HasExtension(opts, confv1.E_Section) && proto.GetExtension(opts, confv1.E_Section).(bool)
}

func confField(fd protoreflect.FieldDescriptor) *confv1.FieldRule {
	opts := fd.Options()
	if opts == nil || !proto.HasExtension(opts, confv1.E_Field) {
		return nil
	}
	rule, _ := proto.GetExtension(opts, confv1.E_Field).(*confv1.FieldRule)
	return rule
}

func hasConfField(md protoreflect.MessageDescriptor) bool {
	for i := range md.Fields().Len() {
		if confField(md.Fields().Get(i)) != nil {
			return true
		}
	}
	return false
}

func markConfig(md protoreflect.MessageDescriptor, graph map[protoreflect.FullName]bool) {
	if md == nil || md.IsMapEntry() || protoreach.IsWellKnown(md) || graph[md.FullName()] {
		return
	}
	graph[md.FullName()] = true
	for i := range md.Fields().Len() {
		if child := protoreach.ConfigChild(md.Fields().Get(i)); child != nil {
			markConfig(child, graph)
		}
	}
}

// nilCheckEmitter 在父文件为外部无 Apply 的消息生成私有、类型化的集合检查。
type nilCheckEmitter struct {
	filePath string
	messages map[protoreflect.FullName]*protogen.Message
	pending  map[protoreflect.FullName]*protogen.Message
	emitted  map[protoreflect.FullName]bool
}

func needsNilShape(md protoreflect.MessageDescriptor, visited map[protoreflect.FullName]bool) bool {
	if md == nil || visited[md.FullName()] {
		return false
	}
	visited[md.FullName()] = true
	for i := range md.Fields().Len() {
		fd := md.Fields().Get(i)
		if oneof := fd.ContainingOneof(); oneof != nil && !oneof.IsSynthetic() {
			return true
		}
		child := protoreach.ConfigChild(fd)
		if child != nil && (fd.IsList() || fd.IsMap() || needsNilShape(child, visited)) {
			return true
		}
	}
	return false
}

func (e *nilCheckEmitter) register(md protoreflect.MessageDescriptor) (string, error) {
	m := e.messages[md.FullName()]
	if m == nil {
		return "", fmt.Errorf("%s: missing child descriptor for nil collection check", md.FullName())
	}
	e.pending[md.FullName()] = m
	h := fnv.New64a()
	_, _ = h.Write([]byte(e.filePath + "|" + string(md.FullName())))
	return fmt.Sprintf("_servoraConfCheckNil_%016x", h.Sum64()), nil
}

func (e *nilCheckEmitter) emitAll(g *protogen.GeneratedFile) error {
	for {
		var names []protoreflect.FullName
		for name := range e.pending {
			if !e.emitted[name] {
				names = append(names, name)
			}
		}
		if len(names) == 0 {
			return nil
		}
		sort.Slice(names, func(i, j int) bool { return names[i] < names[j] })
		for _, name := range names {
			e.emitted[name] = true
			if err := e.emitOne(g, e.pending[name]); err != nil {
				return err
			}
		}
	}
}

func (e *nilCheckEmitter) emitOne(g *protogen.GeneratedFile, m *protogen.Message) error {
	name, _ := e.register(m.Desc)
	fmtErrorf := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Errorf", GoImportPath: "fmt"})
	g.P("func ", name, "(v *", g.QualifiedGoIdent(m.GoIdent), ") error {")
	g.P("if v == nil { return nil }")
	for _, f := range m.Fields {
		fd := f.Desc
		child := protoreach.ConfigChild(fd)
		field := strconv.Quote(string(fd.Name()))
		childHelper := ""
		if child != nil && needsNilShape(child, map[protoreflect.FullName]bool{}) {
			var err error
			childHelper, err = e.register(child)
			if err != nil {
				return err
			}
		}
		if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
			g.P("if selected, ok := v.", f.Oneof.GoName, ".(*", g.QualifiedGoIdent(f.GoIdent), "); ok {")
			g.P("if selected == nil { return ", fmtErrorf, "(\"%s: nil oneof branch\", ", field, ") }")
			if child != nil {
				g.P("if selected.", f.GoName, " == nil { return ", fmtErrorf, "(\"%s: nil message\", ", field, ") }")
				if childHelper != "" {
					g.P("if err := ", childHelper, "(selected.", f.GoName, "); err != nil { return ", fmtErrorf, "(\"%s: %w\", ", field, ", err) }")
				}
			}
			g.P("}")
			continue
		}
		if child == nil {
			continue
		}
		if fd.IsMap() {
			fmtSprint := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Sprint", GoImportPath: "fmt"})
			sortSlice := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Slice", GoImportPath: "sort"})
			g.P("{")
			g.P("keys := make([]", mapKeyType(fd.MapKey().Kind()), ", 0, len(v.", f.GoName, "))")
			g.P("for key := range v.", f.GoName, " { keys = append(keys, key) }")
			g.P(sortSlice, "(keys, func(i, j int) bool { return ", mapLess(fd.MapKey().Kind()), " })")
			g.P("for _, key := range keys {")
			g.P("item := v.", f.GoName, "[key]")
			g.P("if item == nil { return ", fmtErrorf, "(\"%s[%q]: nil message\", ", field, ", ", fmtSprint, "(key)) }")
			if childHelper != "" {
				g.P("if err := ", childHelper, "(item); err != nil { return ", fmtErrorf, "(\"%s[%q]: %w\", ", field, ", ", fmtSprint, "(key), err) }")
			}
			g.P("}")
			g.P("}")
		} else if fd.IsList() {
			g.P("for i, item := range v.", f.GoName, " {")
			g.P("if item == nil { return ", fmtErrorf, "(\"%s[%d]: nil message\", ", field, ", i) }")
			if childHelper != "" {
				g.P("if err := ", childHelper, "(item); err != nil { return ", fmtErrorf, "(\"%s[%d]: %w\", ", field, ", i, err) }")
			}
			g.P("}")
		} else if childHelper != "" {
			g.P("if v.", f.GoName, " != nil {")
			g.P("if err := ", childHelper, "(v.", f.GoName, "); err != nil { return ", fmtErrorf, "(\"%s: %w\", ", field, ", err) }")
			g.P("}")
		}
	}
	g.P("return nil")
	g.P("}")
	g.P()
	return nil
}

func emitApply(g *protogen.GeneratedFile, m *protogen.Message, graph map[protoreflect.FullName]bool, checks *nilCheckEmitter) error {
	md := m.Desc
	for _, f := range m.Fields {
		if err := checkField(f); err != nil {
			return err
		}
	}
	for i := range md.Oneofs().Len() {
		oneof := md.Oneofs().Get(i)
		if oneof.IsSynthetic() {
			continue
		}
		var first protoreflect.FieldDescriptor
		for j := range oneof.Fields().Len() {
			field := oneof.Fields().Get(j)
			if rule := confField(field); rule != nil && rule.GetRequired() {
				if first != nil {
					return fmt.Errorf("%s and %s: mutually exclusive oneof members cannot both be required", first.FullName(), field.FullName())
				}
				first = field
			}
		}
	}
	needsErrors := false
	for _, f := range m.Fields {
		if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
			needsErrors = true
		}
	}
	for _, f := range m.Fields {
		if rule := confField(f.Desc); rule != nil && rule.GetRequired() {
			needsErrors = true
		}
		if child := protoreach.ConfigChild(f.Desc); child != nil && graph[child.FullName()] &&
			(child.ParentFile().Path() == md.ParentFile().Path() || hasStandaloneApply(child) || subtreeHasValidation(child, map[protoreflect.FullName]bool{}) || needsNilShape(child, map[protoreflect.FullName]bool{}) || f.Desc.IsList() || f.Desc.IsMap() || (f.Oneof != nil && !f.Oneof.Desc.IsSynthetic())) {
			needsErrors = true
		}
	}
	fmtErrorf := ""
	if needsErrors {
		fmtErrorf = g.QualifiedGoIdent(protogen.GoIdent{GoName: "Errorf", GoImportPath: "fmt"})
	}
	g.P("// Apply 检查字段设置状态、补充缺失的默认值并处理实际存在的子配置及本层值约束。")
	g.P("func (m *", m.GoIdent.GoName, ") Apply() error {")
	g.P("if m == nil { return nil }")
	for _, f := range m.Fields {
		if rule := confField(f.Desc); rule != nil && rule.GetRequired() {
			predicate := "m." + f.GoName + " == nil"
			if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
				predicate = "!is" + f.GoName
				g.P("_, is", f.GoName, " := m.", f.Oneof.GoName, ".(*", f.GoIdent.GoName, ")")
			}
			g.P("if ", predicate, " { return ", fmtErrorf, "(", strconv.Quote(string(f.Desc.Name())+" is required"), ") }")
		}
	}
	for _, f := range m.Fields {
		if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
			g.P("if selected, ok := m.", f.Oneof.GoName, ".(*", f.GoIdent.GoName, "); ok && selected == nil {")
			g.P("return ", fmtErrorf, "(\"%s: nil oneof branch\", ", strconv.Quote(string(f.Desc.Name())), ")")
			g.P("}")
		}
	}
	for _, f := range m.Fields {
		if rule := confField(f.Desc); rule != nil && rule.Default != nil {
			if err := emitDefault(g, f, *rule.Default); err != nil {
				return fmt.Errorf("%s: %w", f.Desc.FullName(), err)
			}
		}
	}
	for _, f := range m.Fields {
		child := protoreach.ConfigChild(f.Desc)
		if child == nil || !graph[child.FullName()] {
			continue
		}
		applyChild := child.ParentFile().Path() == md.ParentFile().Path() || hasStandaloneApply(child)
		validateChild := !applyChild && subtreeHasValidation(child, map[protoreflect.FullName]bool{})
		if validateChild && subtreeHasIgnore(child, map[protoreflect.FullName]bool{}) {
			return fmt.Errorf("%s: buf.validate ignore is unsupported in configuration", f.Desc.FullName())
		}
		nilHelper := ""
		if !applyChild && needsNilShape(child, map[protoreflect.FullName]bool{}) {
			var err error
			nilHelper, err = checks.register(child)
			if err != nil {
				return fmt.Errorf("%s: %w", f.Desc.FullName(), err)
			}
		}
		if !applyChild && !validateChild && nilHelper == "" && !f.Desc.IsMap() && !f.Desc.IsList() && (f.Oneof == nil || f.Oneof.Desc.IsSynthetic()) {
			continue
		}
		name := strconv.Quote(string(f.Desc.Name()))
		if f.Desc.IsMap() {
			fmtSprint := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Sprint", GoImportPath: "fmt"})
			sortSlice := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Slice", GoImportPath: "sort"})
			keyType := mapKeyType(f.Desc.MapKey().Kind())
			g.P("{")
			g.P("keys := make([]", keyType, ", 0, len(m.", f.GoName, "))")
			g.P("for key := range m.", f.GoName, " { keys = append(keys, key) }")
			g.P(sortSlice, "(keys, func(i, j int) bool { return ", mapLess(f.Desc.MapKey().Kind()), " })")
			g.P("for _, key := range keys {")
			g.P("v := m.", f.GoName, "[key]")
			g.P("if v == nil { return ", fmtErrorf, "(\"%s[%q]: nil message\", ", name, ", ", fmtSprint, "(key)) }")
			if applyChild {
				g.P("if err := v.Apply(); err != nil { return ", fmtErrorf, "(\"%s[%q]: %w\", ", name, ", ", fmtSprint, "(key), err) }")
			}
			if nilHelper != "" {
				g.P("if err := ", nilHelper, "(v); err != nil { return ", fmtErrorf, "(\"%s[%q]: %w\", ", name, ", ", fmtSprint, "(key), err) }")
			}
			if validateChild {
				emitFullValidation(g, "v", fmt.Sprintf("return %s(\"%%s[%%q]: %%w\", %s, %s(key), err)", fmtErrorf, name, fmtSprint))
			}
			g.P("}")
			g.P("}")
		} else if f.Desc.IsList() {
			g.P("for i, v := range m.", f.GoName, " {")
			g.P("if v == nil { return ", fmtErrorf, "(\"%s[%d]: nil message\", ", name, ", i) }")
			if applyChild {
				g.P("if err := v.Apply(); err != nil { return ", fmtErrorf, "(\"%s[%d]: %w\", ", name, ", i, err) }")
			}
			if nilHelper != "" {
				g.P("if err := ", nilHelper, "(v); err != nil { return ", fmtErrorf, "(\"%s[%d]: %w\", ", name, ", i, err) }")
			}
			if validateChild {
				emitFullValidation(g, "v", fmt.Sprintf("return %s(\"%%s[%%d]: %%w\", %s, i, err)", fmtErrorf, name))
			}
			g.P("}")
		} else if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
			g.P("if selected, ok := m.", f.Oneof.GoName, ".(*", f.GoIdent.GoName, "); ok {")
			g.P("if selected == nil || selected.", f.GoName, " == nil { return ", fmtErrorf, "(\"%s: nil message\", ", name, ") }")
			if applyChild {
				g.P("if err := selected.", f.GoName, ".Apply(); err != nil { return ", fmtErrorf, "(\"%s: %w\", ", name, ", err) }")
			}
			if nilHelper != "" {
				g.P("if err := ", nilHelper, "(selected.", f.GoName, "); err != nil { return ", fmtErrorf, "(\"%s: %w\", ", name, ", err) }")
			}
			if validateChild {
				emitFullValidation(g, "selected."+f.GoName, fmt.Sprintf("return %s(\"%%s: %%w\", %s, err)", fmtErrorf, name))
			}
			g.P("}")
		} else {
			g.P("if m.", f.GoName, " != nil {")
			if applyChild {
				g.P("if err := m.", f.GoName, ".Apply(); err != nil { return ", fmtErrorf, "(\"%s: %w\", ", name, ", err) }")
			}
			if nilHelper != "" {
				g.P("if err := ", nilHelper, "(m.", f.GoName, "); err != nil { return ", fmtErrorf, "(\"%s: %w\", ", name, ", err) }")
			}
			if validateChild {
				emitFullValidation(g, "m."+f.GoName, fmt.Sprintf("return %s(\"%%s: %%w\", %s, err)", fmtErrorf, name))
			}
			g.P("}")
		}
	}
	if hasValidation(md) {
		pv := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Validate", GoImportPath: "buf.build/go/protovalidate"})
		withFilter := g.QualifiedGoIdent(protogen.GoIdent{GoName: "WithFilter", GoImportPath: "buf.build/go/protovalidate"})
		filterFunc := g.QualifiedGoIdent(protogen.GoIdent{GoName: "FilterFunc", GoImportPath: "buf.build/go/protovalidate"})
		reflection := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Descriptor", GoImportPath: "google.golang.org/protobuf/reflect/protoreflect"})
		message := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Message", GoImportPath: "google.golang.org/protobuf/reflect/protoreflect"})
		g.P("if err := ", pv, "(m, ", withFilter, "(", filterFunc, "(func(current ", message, ", _ ", reflection, ") bool {")
		g.P("return current.Interface() == m")
		g.P("}))); err != nil {")
		emitViolationSort(g)
		g.P("return err")
		g.P("}")
	}
	g.P("return nil")
	g.P("}")
	g.P()
	return nil
}

// emitViolationSort 仅在校验失败时整理违规路径，保留原始错误类型。
func emitViolationSort(g *protogen.GeneratedFile) {
	validationError := g.QualifiedGoIdent(protogen.GoIdent{GoName: "ValidationError", GoImportPath: "buf.build/go/protovalidate"})
	pathString := g.QualifiedGoIdent(protogen.GoIdent{GoName: "FieldPathString", GoImportPath: "buf.build/go/protovalidate"})
	sortSlice := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Slice", GoImportPath: "sort"})
	g.P("if violations, ok := err.(*", validationError, "); ok {")
	g.P(sortSlice, "(violations.Violations, func(i, j int) bool {")
	g.P("a, b := violations.Violations[i], violations.Violations[j]")
	g.P("left, right := ", pathString, "(a.Proto.GetField()), ", pathString, "(b.Proto.GetField())")
	g.P("if left != right { return left < right }")
	g.P("if a.Proto.GetForKey() != b.Proto.GetForKey() { return a.Proto.GetForKey() }")
	g.P("return a.String() < b.String()")
	g.P("})")
	g.P("}")
}

// emitFullValidation 处理没有配置注解、但包含值约束的外部子消息。
func emitFullValidation(g *protogen.GeneratedFile, expression, onError string) {
	validateCall := g.QualifiedGoIdent(protogen.GoIdent{GoName: "Validate", GoImportPath: "buf.build/go/protovalidate"})
	g.P("if err := ", validateCall, "(", expression, "); err != nil {")
	emitViolationSort(g)
	g.P(onError)
	g.P("}")
}

func hasStandaloneApply(md protoreflect.MessageDescriptor) bool {
	return reachesOwnAnnotation(md, map[protoreflect.FullName]bool{})
}

func reachesOwnAnnotation(md protoreflect.MessageDescriptor, visited map[protoreflect.FullName]bool) bool {
	if md == nil || visited[md.FullName()] {
		return false
	}
	visited[md.FullName()] = true
	if section(md) || hasConfField(md) {
		return true
	}
	for i := range md.Fields().Len() {
		if reachesOwnAnnotation(protoreach.ConfigChild(md.Fields().Get(i)), visited) {
			return true
		}
	}
	return false
}

func subtreeHasValidation(md protoreflect.MessageDescriptor, visited map[protoreflect.FullName]bool) bool {
	if md == nil || visited[md.FullName()] {
		return false
	}
	visited[md.FullName()] = true
	if hasValidation(md) {
		return true
	}
	for i := range md.Fields().Len() {
		if subtreeHasValidation(protoreach.ConfigChild(md.Fields().Get(i)), visited) {
			return true
		}
	}
	return false
}

func subtreeHasIgnore(md protoreflect.MessageDescriptor, visited map[protoreflect.FullName]bool) bool {
	if md == nil || visited[md.FullName()] {
		return false
	}
	visited[md.FullName()] = true
	for i := range md.Fields().Len() {
		fd := md.Fields().Get(i)
		if opts := fd.Options(); opts != nil && proto.HasExtension(opts, validate.E_Field) {
			if rules, ok := proto.GetExtension(opts, validate.E_Field).(*validate.FieldRules); ok && hasIgnore(rules) {
				return true
			}
		}
		if subtreeHasIgnore(protoreach.ConfigChild(fd), visited) {
			return true
		}
	}
	return false
}

func checkField(f *protogen.Field) error {
	fd := f.Desc
	if opts := fd.Options(); opts != nil && proto.HasExtension(opts, validate.E_Field) {
		if rules, ok := proto.GetExtension(opts, validate.E_Field).(*validate.FieldRules); ok && hasIgnore(rules) {
			return fmt.Errorf("%s: buf.validate ignore is unsupported in configuration", fd.FullName())
		}
	}
	rule := confField(fd)
	if rule == nil {
		return nil
	}
	if rule.Default != nil && rule.GetRequired() {
		return fmt.Errorf("%s: default and required conflict", fd.FullName())
	}
	if !rule.GetRequired() && rule.Default == nil {
		return fmt.Errorf("%s: empty conf field rule", fd.FullName())
	}
	if fd.IsList() || fd.IsMap() {
		return fmt.Errorf("%s: collection default/required is unsupported; use buf.validate for nonempty collections", fd.FullName())
	}
	if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() && rule.Default != nil {
		return fmt.Errorf("%s: oneof default is unsupported", fd.FullName())
	}
	if !fd.HasPresence() {
		return fmt.Errorf("%s: conf default/required requires an explicitly settable field", fd.FullName())
	}
	if rule.Default != nil {
		switch fd.Kind() {
		case protoreflect.StringKind, protoreflect.BoolKind,
			protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind,
			protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
			protoreflect.Uint32Kind, protoreflect.Fixed32Kind, protoreflect.Uint64Kind, protoreflect.Fixed64Kind,
			protoreflect.FloatKind, protoreflect.DoubleKind:
			return nil
		case protoreflect.MessageKind:
			if fd.Message().FullName() == "google.protobuf.Duration" {
				return nil
			}
		}
		return fmt.Errorf("%s: unsupported default kind %s", fd.FullName(), fd.Kind())
	}
	return nil
}

func hasIgnore(rules *validate.FieldRules) bool {
	if rules == nil {
		return false
	}
	if rules.GetIgnore() != validate.Ignore_IGNORE_UNSPECIFIED {
		return true
	}
	return hasIgnore(rules.GetRepeated().GetItems()) ||
		hasIgnore(rules.GetMap().GetKeys()) || hasIgnore(rules.GetMap().GetValues())
}

func emitDefault(g *protogen.GeneratedFile, f *protogen.Field, literal string) error {
	var expr string
	var err error
	switch f.Desc.Kind() {
	case protoreflect.StringKind:
		expr = strconv.Quote(literal)
	case protoreflect.BoolKind:
		var v bool
		v, err = strconv.ParseBool(literal)
		expr = strconv.FormatBool(v)
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		var v int64
		v, err = strconv.ParseInt(literal, 10, 32)
		expr = strconv.FormatInt(v, 10)
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		var v int64
		v, err = strconv.ParseInt(literal, 10, 64)
		expr = strconv.FormatInt(v, 10)
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		var v uint64
		v, err = strconv.ParseUint(literal, 10, 32)
		expr = strconv.FormatUint(v, 10)
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		var v uint64
		v, err = strconv.ParseUint(literal, 10, 64)
		expr = strconv.FormatUint(v, 10)
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		bits := 64
		if f.Desc.Kind() == protoreflect.FloatKind {
			bits = 32
		}
		var v float64
		v, err = strconv.ParseFloat(literal, bits)
		if err == nil && (math.IsNaN(v) || math.IsInf(v, 0)) {
			err = fmt.Errorf("non-finite number")
		}
		expr = strconv.FormatFloat(v, 'g', -1, bits)
		if bits == 32 {
			expr = "float32(" + expr + ")"
		} else {
			expr = "float64(" + expr + ")"
		}
	case protoreflect.MessageKind:
		var d time.Duration
		d, err = time.ParseDuration(literal)
		if err == nil {
			newDuration := g.QualifiedGoIdent(protogen.GoIdent{GoName: "New", GoImportPath: "google.golang.org/protobuf/types/known/durationpb"})
			expr = fmt.Sprintf("%s(%d)", newDuration, int64(d))
		}
	default:
		return fmt.Errorf("unsupported default kind %s", f.Desc.Kind())
	}
	if err != nil {
		return fmt.Errorf("invalid default %q: %w", literal, err)
	}
	g.P("if m.", f.GoName, " == nil {")
	if f.Desc.Kind() == protoreflect.MessageKind {
		g.P("m.", f.GoName, " = ", expr)
	} else {
		g.P("value := ", typedDefault(f.Desc.Kind(), expr))
		g.P("m.", f.GoName, " = &value")
	}
	g.P("}")
	return nil
}

func typedDefault(kind protoreflect.Kind, expr string) string {
	switch kind {
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32(" + expr + ")"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64(" + expr + ")"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32(" + expr + ")"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return "uint64(" + expr + ")"
	default:
		return expr
	}
}

func hasValidation(md protoreflect.MessageDescriptor) bool {
	if opts := md.Options(); opts != nil && proto.HasExtension(opts, validate.E_Message) {
		return true
	}
	for i := range md.Fields().Len() {
		if opts := md.Fields().Get(i).Options(); opts != nil && proto.HasExtension(opts, validate.E_Field) {
			return true
		}
	}
	for i := range md.Oneofs().Len() {
		if opts := md.Oneofs().Get(i).Options(); opts != nil && proto.HasExtension(opts, validate.E_Oneof) {
			return true
		}
	}
	return false
}

func mapKeyType(kind protoreflect.Kind) string {
	switch kind {
	case protoreflect.StringKind:
		return "string"
	case protoreflect.BoolKind:
		return "bool"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		return "int32"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		return "int64"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		return "uint32"
	default:
		return "uint64"
	}
}

func mapLess(kind protoreflect.Kind) string {
	if kind == protoreflect.BoolKind {
		return "!keys[i] && keys[j]"
	}
	return "keys[i] < keys[j]"
}
